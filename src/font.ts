/** Width in pixels of a rendered string (0 for an empty string). */
export function textWidth(text: string): number {
  const n = [...text].length
  return n === 0 ? 0 : n * GLYPH_WIDTH + (n - 1) * GLYPH_GAP
}

/**
 * Returns the lit pixels of a string as [x, y] pairs, relative to its top left corner.
 * Characters without a glyph are skipped but still take their place as a blank.
 */
export function textPixels(text: string): [number, number][] {
  const out: [number, number][] = []
  let ox = 0
  for (const ch of text) {
    const glyph = GLYPHS[ch]
    if (glyph) {
      glyph.forEach((row, y) => {
        for (let x = 0; x < GLYPH_WIDTH; x++) if (row[x] === '#') out.push([ox + x, y])
      })
    }
    ox += GLYPH_WIDTH + GLYPH_GAP
  }
  return out
}
